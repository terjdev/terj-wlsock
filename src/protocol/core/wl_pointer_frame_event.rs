/// Server event `wl_pointer.frame`.
///
/// Opcode 5; available since version 5. The structure contains the receiver and arguments in XML order.
/// Encoding and decoding check wire values and receiver metadata; compositor semantics are not validated.
/// Decoding consumes the complete payload and updates wire object metadata when needed.
/// The caller handles compositor policy and message contents.
/// ```xml
/// <event name="frame" since="5">
///       <description summary="end of a pointer event sequence">
///         Indicates the end of a set of events that logically belong together.
///         A client is expected to accumulate the data in all events within the
///         frame before proceeding.
///
///         All wl_pointer events before a wl_pointer.frame event belong
///         logically together. For example, in a diagonal scroll motion the
///         compositor will send an optional wl_pointer.axis_source event, two
///         wl_pointer.axis events (horizontal and vertical) and finally a
///         wl_pointer.frame event. The client may use this information to
///         calculate a diagonal vector for scrolling.
///
///         When multiple wl_pointer.axis events occur within the same frame,
///         the motion vector is the combined motion of all events.
///         When a wl_pointer.axis and a wl_pointer.axis_stop event occur within
///         the same frame, this indicates that axis movement in one axis has
///         stopped but continues in the other axis.
///         When multiple wl_pointer.axis_stop events occur within the same
///         frame, this indicates that these axes stopped in the same instance.
///
///         A wl_pointer.frame event is sent for every logical event group,
///         even if the group only contains a single wl_pointer event.
///         Specifically, a client may get a sequence: motion, frame, button,
///         frame, axis, frame, axis_stop, frame.
///
///         The wl_pointer.enter and wl_pointer.leave events are logical events
///         generated by the compositor and not the hardware. These events are
///         also grouped by a wl_pointer.frame. When a pointer moves from one
///         surface to another, a compositor should group the
///         wl_pointer.leave event within the same wl_pointer.frame.
///         However, a client must not rely on wl_pointer.leave and
///         wl_pointer.enter being in the same wl_pointer.frame.
///         Compositor-specific policies may require the wl_pointer.leave and
///         wl_pointer.enter event being split across multiple wl_pointer.frame
///         groups.
///       </description>
///     </event>
/// ```
#[derive(Debug)]
pub struct WlPointerFrameEvent {
    /// Wire identifier of the object receiving the message.
    pub object_id: u32,
}
impl WlPointerFrameEvent {
    /// Opcode in the event namespace of interface wl_pointer.
    pub const OPCODE: u16 = 5;
    /// Minimum interface version supporting this message.
    pub const SINCE: u32 = 5;
}
impl CommandWriter for WlPointerFrameEvent {
    fn object_id(&self) -> u32 {
        self.object_id
    }
    fn opcode(&self) -> u16 {
        Self::OPCODE
    }
    fn payload_size(&self) -> usize {
        Self::total_payload_size(&[])
    }
    async fn write(
        self,
        writer: &mut FdPayloadWriter<'_>,
        state: &Arc<Mutex<ClientState>>,
    ) -> Result<(), FdWriterError> {
        Self::writer_event_interface(state, self.object_id, "wl_pointer", Self::SINCE)?;
        if self.payload_size() != writer.remaining_quota() {
            return Err(FdWriterError::InvalidProtocol);
        }
        Ok(())
    }
}

impl CommandReader<Self> for WlPointerFrameEvent {
    async fn read(
        object_id: u32,
        opcode: u16,
        reader: &mut FdPayloadReader<'_>,
        state: &Arc<Mutex<ClientState>>,
    ) -> Result<Self, FdReaderError> {
        let interface = Self::reader_state(state)?
            .object_interface(object_id)
            .ok_or(FdReaderError::InvalidProtocol)?;
        Self::read_with_interface(object_id, opcode, interface, reader, state).await
    }
}

impl InterfaceReader for WlPointerFrameEvent {
    async fn read_with_interface(
        object_id: u32,
        opcode: u16,
        interface: ObjectInteface,
        reader: &mut FdPayloadReader<'_>,
        _state: &Arc<Mutex<ClientState>>,
    ) -> Result<Self, FdReaderError> {
        if !matches!(interface, ObjectInteface::WlPointer { .. })
            || opcode != Self::OPCODE
            || interface.version() < Self::SINCE
        {
            return Err(FdReaderError::InvalidProtocol);
        }
        if reader.remaining_quota() != 0 {
            return Err(FdReaderError::InvalidProtocol);
        }
        Ok(Self { object_id })
    }
}
