/// Client request `xdg_activation_token_v1.set_surface`.
///
/// Opcode 2; available since version 1.
/// Wire framing and receiver metadata are checked; protocol semantics belong to the caller.
/// ```xml
/// <request name="set_surface">
///       <description summary="specifies the surface requesting activation">
///         This request sets the surface requesting the activation. Note, this is
///         different from the surface that will be activated.
///
///         Some compositors might refuse to activate toplevels when the token
///         doesn't have a requesting surface.
///
///         Must be sent before commit. This information is optional.
///       </description>
///       <arg name="surface" type="object" interface="wl_surface" summary="the requesting surface" />
///     </request>
/// ```
#[derive(Debug)]
pub struct XdgActivationTokenV1SetSurfaceRequest {
    /// Wire identifier of the receiver.
    pub object_id: u32,
    /// the requesting surface.
    pub surface: u32,
}
impl XdgActivationTokenV1SetSurfaceRequest {
    /// Opcode in the request namespace.
    pub const OPCODE: u16 = 2;
    /// Minimum supported interface version.
    pub const SINCE: u32 = 1;
}
impl CommandReader<Self> for XdgActivationTokenV1SetSurfaceRequest {
    async fn read(
        object_id: u32,
        opcode: u16,
        reader: &mut FdPayloadReader<'_>,
        state: &Arc<Mutex<ClientState>>,
    ) -> Result<Self, FdReaderError> {
        let interface = Self::reader_state(state)?
            .object_interface(object_id)
            .ok_or(FdReaderError::InvalidProtocol)?;
        Self::read_with_interface(object_id, opcode, interface, reader, state).await
    }
}
impl InterfaceReader for XdgActivationTokenV1SetSurfaceRequest {
    async fn read_with_interface(
        object_id: u32,
        opcode: u16,
        interface: ObjectInteface,
        reader: &mut FdPayloadReader<'_>,
        _state: &Arc<Mutex<ClientState>>,
    ) -> Result<Self, FdReaderError> {
        if !matches!(
            interface,
            ObjectInteface::XdgActivation(XdgActivationObjectInteface::XdgActivationTokenV1 { .. })
        ) || opcode != Self::OPCODE
            || interface.version() < Self::SINCE
        {
            return Err(FdReaderError::InvalidProtocol);
        }
        let surface = reader.next_u32().await?;
        if reader.remaining_quota() != 0 {
            return Err(FdReaderError::InvalidProtocol);
        }
        Ok(Self { object_id, surface })
    }
}
impl CommandWriter for XdgActivationTokenV1SetSurfaceRequest {
    fn object_id(&self) -> u32 {
        self.object_id
    }
    fn opcode(&self) -> u16 {
        Self::OPCODE
    }
    fn payload_size(&self) -> usize {
        Self::total_payload_size(&[Some(4)])
    }
    async fn write(
        self,
        writer: &mut FdPayloadWriter<'_>,
        state: &Arc<Mutex<ClientState>>,
    ) -> Result<(), FdWriterError> {
        Self::writer_request_interface(
            state,
            self.object_id,
            "xdg_activation_token_v1",
            Self::SINCE,
        )?;
        if self.payload_size() != writer.remaining_quota() {
            return Err(FdWriterError::InvalidProtocol);
        }
        writer.next_u32(self.surface).await?;
        Ok(())
    }
}
